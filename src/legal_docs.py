def _support_line() -> str:
    url = (config.SUPPORT_URL or "").strip()
    email = (getattr(config, "SUPPORT_EMAIL", "") or "").strip()
    parts: list[str] = []
    if url:
        parts.append(url)
    if email:
        parts.append(email)
    return " · ".join(parts) if parts else "через Telegram-бота"


